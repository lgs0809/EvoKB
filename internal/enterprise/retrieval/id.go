package retrieval

import (
	"crypto/rand"
	"encoding/hex"
)

func newSearchID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "00000000-0000-4000-8000-000000000000"
	}
	// RFC 4122 variant/version bits keep persisted search IDs compatible with
	// the CHAR(36) audit schema without coupling search to a database driver.
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	x := hex.EncodeToString(b[:])
	return x[0:8] + "-" + x[8:12] + "-" + x[12:16] + "-" + x[16:20] + "-" + x[20:32]
}
