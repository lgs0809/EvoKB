-- Native multipart facts are in MinIO. PostgreSQL owns identity, permission and transitions.
CREATE TABLE kb_upload_session (
 session_id VARCHAR(36) PRIMARY KEY,
 user_id VARCHAR(36) NOT NULL REFERENCES enterprise_user(user_id),
 username VARCHAR(64) NOT NULL,
 knowledge_base_id VARCHAR(128) NOT NULL,
 bucket VARCHAR(255) NOT NULL,
 object_key VARCHAR(2048) NOT NULL UNIQUE,
 upload_id TEXT,
 filename VARCHAR(512) NOT NULL,
 relative_path VARCHAR(1024) NOT NULL,
 expected_bytes BIGINT NOT NULL CHECK(expected_bytes>0),
 part_size INTEGER NOT NULL CHECK(part_size=16777216),
 part_count INTEGER NOT NULL CHECK(part_count BETWEEN 1 AND 16),
 client_sha256 VARCHAR(64),
 metadata_json JSONB NOT NULL,
 status VARCHAR(32) NOT NULL CHECK(status IN ('UPLOADING','COMPLETING','COMPLETED','ABORTED','EXPIRED')),
 revision BIGINT NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP+interval '24 hours',
 completion_owner VARCHAR(36),
 completion_deadline TIMESTAMPTZ,
 completion_parts JSONB,
 completion_parts_sha256 VARCHAR(64),
 object_etag TEXT,
 object_version TEXT,
 document_id VARCHAR(36) REFERENCES document(document_id),
 document_version_id VARCHAR(36) UNIQUE REFERENCES document_version(version_id),
 batch_id VARCHAR(36) UNIQUE REFERENCES ingestion_batch(batch_id),
 file_id VARCHAR(36) UNIQUE REFERENCES ingestion_file(file_id),
 abort_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
 completed_at TIMESTAMPTZ,
 integrity_status VARCHAR(32) NOT NULL DEFAULT 'UNVERIFIED' CHECK(integrity_status IN ('UNVERIFIED','VERIFIED','FAILED')),
 actual_sha256 VARCHAR(64),
 CHECK(expires_at=created_at+interval '24 hours'),
 CHECK(client_sha256 IS NULL OR client_sha256 ~ '^[0-9a-f]{64}$'),
 CHECK((status='COMPLETED')=(document_version_id IS NOT NULL AND batch_id IS NOT NULL AND file_id IS NOT NULL))
);
CREATE INDEX upload_session_recovery ON kb_upload_session(status,expires_at,completion_deadline,session_id);
ALTER TABLE ingestion_file ADD COLUMN upload_session_id VARCHAR(36) UNIQUE REFERENCES kb_upload_session(session_id);
