package cn.lgs.knowledgebase.application.ask;

/** One scope contract for retrieval decisions, answer generation and delivery verification. */
public final class EvidenceScopePolicy {
  private EvidenceScopePolicy() {}

  public static String instructions() {
    return "区分原文支持的事实、本次可见检索未命中，以及全库或现实中不存在。有限检索不能证明后者。"
        + "当前原文未覆盖指定对象时，可以说明在本次可见检索资料中尚未找到其原文，因此不能确认所问事实；"
        + "除非用户明确要求全库覆盖审计，不把证明全库不存在作为必须补齐的缺项反复检索。"
        + "只有存在能够补齐用户所问事实的具体新线索才继续补搜。"
        + "缺少目标对象原文时，除非用户要求比较，不罗列其他对象的金额、期限等无关事实。"
        + "无法确认的回答也应引用实际查看的原文来说明本次资料范围。引用只证明已查看资料的对象标识或范围时，"
        + "核验其范围说明即可，不要求它证明尚未检出的目标对象的事实或全库不存在；不能借此移植其他对象的事实。"
        + "来源引用与原文访问入口由应用负责呈现：有效引用[n]绑定已授权证据，回答只需引用对应原文。"
        + "用户要求能打开的原文依据时，提供相应引用；原文没有写访问网址不表示系统不能展示原文，也不是需要补搜的业务事实。"
        + "不主动罗列平台内部证据ID、文档版本ID、对象存储路径，也不编造下载地址或让用户手工用这些内部参数定位原文。"
        + "用户明确询问原文记载的业务编号或网址时仍应如实回答，并保留出处；它们与平台内部元数据不同。"
        + "核验时，错误推断系统原文访问能力、要求用户用内部参数寻找原文，同样是应在原事实和相同证据上修订的交付问题，不应触发无关补搜。";
  }
}
